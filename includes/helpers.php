		if ( is_array( $cached ) ) {
			return $cached;
		}

		$body = hw_hub_api_get(
			untrailingslashit( HW_HUB_API_BASE ) . '/city/hostel/' . $city_id . '/properties/?currency=' . rawurlencode( $args['currency'] )
		);

		$out = array();

		foreach ( ( isset( $body['data']['properties'] ) ? $body['data']['properties'] : array() ) as $property ) {
			$out[] = array(
				'id'       => isset( $property['id'] ) ? (int) $property['id'] : 0,
				'name'     => isset( $property['name'] ) ? $property['name'] : '',
				'city'     => isset( $property['city'] ) ? $property['city'] : '',
				'country'  => isset( $property['country'] ) ? $property['country'] : '',
				'rating'   => isset( $property['avgRating'] ) ? (float) $property['avgRating'] : 0,
				'reviews'  => isset( $property['numberReviews'] ) ? (int) $property['numberReviews'] : 0,
				'distance' => isset( $property['cityCenterDistance'] ) ? (float) $property['cityCenterDistance'] : null,
				// A dorm price of 0 means "no dorms" (hotels, guesthouses), not free beds.
				'price'    => ! empty( $property['sharedMinPrice']['value'] ) && (float) $property['sharedMinPrice']['value'] > 0 ? $property['sharedMinPrice'] : ( ! empty( $property['privateMinPrice']['value'] ) && (float) $property['privateMinPrice']['value'] > 0 ? $property['privateMinPrice'] : null ),
				'dorm'     => ! empty( $property['sharedMinPrice']['value'] ) && (float) $property['sharedMinPrice']['value'] > 0,
				'type'     => isset( $property['type'] ) ? strtoupper( (string) $property['type'] ) : '',
				'image'    => hw_hub_api_image( $property ),
				'url'      => hw_hub_api_property_url( $property ),
				'eco'      => ! empty( $property['sustainability'][0]['category_title'] ) ? $property['sustainability'][0]['category_title'] : '',
				'lat'      => isset( $property['geoCoordinates']['latitude'] ) ? (float) $property['geoCoordinates']['latitude'] : 0,
				'lng'      => isset( $property['geoCoordinates']['longitude'] ) ? (float) $property['geoCoordinates']['longitude'] : 0,
			);
		}

		// Thin samples held back, as on the other hubs: a 10 from 40 reviews is
		// not what a reader means by the best hostel in the city.
		$min    = (int) $args['min_reviews'];
		$strong = array_values(
			array_filter(
				$out,
				function ( $item ) use ( $min ) {
					return $item['reviews'] >= $min;
				}
			)
		);

		if ( count( $strong ) >= 4 ) {
			$out = $strong;
		}

		usort(
			$out,
			function ( $a, $b ) {
				if ( $a['rating'] === $b['rating'] ) {
					return $b['reviews'] <=> $a['reviews'];
				}

				return $b['rating'] <=> $a['rating'];
			}
		);

		$out = array_slice( $out, 0, max( 1, (int) $args['limit'] ) );

		return hw_hub_api_remember( $key, $out, $args['hours'] );
	}
}

/* ---------- Breadcrumbs ---------------------------------------------------- */

if ( ! function_exists( 'hw_hub_page_title' ) ) {
	/**
	 * A Page's plain title. get_the_title() adds "Private:" or "Protected:"
	 * in front of private and password-protected Pages, which must never
	 * show up in a breadcrumb, a button or structured data.
	 *
	 * @param int $post_id Page ID.
	 * @return string
	 */
	function hw_hub_page_title( $post_id ) {
		return trim( wp_strip_all_tags( (string) get_post_field( 'post_title', $post_id, 'raw' ) ) );
	}
}

if ( ! function_exists( 'hw_hub_breadcrumbs' ) ) {
	/**
	 * The trail from the blog home to this page, built from the Page
	 * hierarchy (Europe > Spain > Barcelona), so it always matches the URL.
	 *
	 * @param int $post_id Page ID.
	 * @return array List of array( name, url ); the last item is this page.
	 */
	function hw_hub_breadcrumbs( $post_id ) {
		$trail = array(
			array(
				'name' => hw_hub_t( 'Blog' ),
				'url'  => home_url( '/' ),
			),
		);

		foreach ( array_reverse( get_post_ancestors( $post_id ) ) as $ancestor_id ) {
			$trail[] = array(
				'name' => hw_hub_page_title( $ancestor_id ),
				'url'  => get_permalink( $ancestor_id ),
			);
		}

		$trail[] = array(
			'name' => hw_hub_page_title( $post_id ),
			'url'  => get_permalink( $post_id ),
		);

		return $trail;
	}
}

if ( ! function_exists( 'hw_hub_render_breadcrumbs' ) ) {
	/**
	 * The back button to the parent guide and the breadcrumb trail, printed
	 * inside the hero, across its top edge.
	 *
	 * @param int    $post_id    Page ID.
	 * @param string $parent_ref Optional page path from the editor (e.g.
	 *                           europe/spain); falls back to the parent Page.
	 * @return void
	 */
	function hw_hub_render_breadcrumbs( $post_id, $parent_ref = '' ) {
		$trail      = hw_hub_breadcrumbs( $post_id );
		$parent     = $parent_ref ? get_page_by_path( $parent_ref ) : null;
		$parent_id  = $parent ? $parent->ID : wp_get_post_parent_id( $post_id );
		$parent_url = $parent_id ? get_permalink( $parent_id ) : '';
		?>
		<div class="hw-hub__hero-crumbs">
			<div class="hw-hub__wrap hw-hub__crumbs-inner">
				<?php if ( $parent_url ) : ?>
					<a class="hw-hub__crumbs-back" href="<?php echo esc_url( $parent_url ); ?>">
						<?php echo hw_hub_icon( 'arrow-left', 16 ); // phpcs:ignore WordPress.Security.EscapeOutput ?>
						<span>
							<?php
							printf(
								/* translators: %s: parent guide, e.g. Spain */
								esc_html( hw_hub_t( 'Back to %s' ) ),
								esc_html( hw_hub_page_title( $parent_id ) )
							);
							?>
						</span>
					</a>
				<?php endif; ?>

				<nav class="hw-hub__crumbs-nav" aria-label="<?php echo esc_attr( hw_hub_t( 'Breadcrumb' ) ); ?>">
					<ol>
						<?php foreach ( $trail as $i => $crumb ) : ?>
							<li>
								<?php if ( count( $trail ) - 1 === $i ) : ?>
									<span aria-current="page"><?php echo esc_html( $crumb['name'] ); ?></span>
								<?php else : ?>
									<a href="<?php echo esc_url( $crumb['url'] ); ?>"><?php echo esc_html( $crumb['name'] ); ?></a>
								<?php endif; ?>
							</li>
						<?php endforeach; ?>
					</ol>
				</nav>
			</div>
		</div>
		<?php
	}
}

/* ---------- Analytics ------------------------------------------------------ */

if ( ! function_exists( 'hw_hub_track' ) ) {
	/**
	 * Data attributes that hub.js reads to send a click event to Google
	 * Analytics (through the dataLayer, for Google Tag Manager).
	 *
	 * @param string $type  What was clicked, e.g. hostel_card, events_cta.
	 * @param string $label Human-readable detail, e.g. the hostel name.
	 * @return string Attribute markup, already escaped.
	 */
	function hw_hub_track( $type, $label = '' ) {
		$out = 'data-hw-track="' . esc_attr( $type ) . '"';

		if ( '' !== (string) $label ) {
			$out .= ' data-hw-track-label="' . esc_attr( wp_strip_all_tags( $label ) ) . '"';
		}

		return $out;
	}
