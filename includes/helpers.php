if ( ! function_exists( 'hw_hub_image' ) ) {
	/**
	 * An image from an attachment ID, a URL, or a bundled WDS illustration
	 * named as illustration:continent-map-europe.
	 *
	 * @param mixed  $image Attachment ID, URL, or illustration reference.
	 * @param string $alt   Alt text.
	 * @param string $size  Image size for attachments.
	 * @return string
	 */
	function hw_hub_image( $image, $alt = '', $size = 'large' ) {
		$image = is_string( $image ) ? trim( $image ) : $image;

		if ( empty( $image ) ) {
			return '';
		}

		if ( is_string( $image ) && 0 === strpos( $image, 'illustration:' ) ) {
			return hw_hub_illustration( substr( $image, 13 ), $alt );
		}

		if ( is_numeric( $image ) ) {
			return wp_get_attachment_image( (int) $image, $size, false, array( 'alt' => $alt, 'loading' => 'lazy' ) );
		}

		return '<img src="' . esc_url( $image ) . '" alt="' . esc_attr( $alt ) . '" loading="lazy">';
	}
}

if ( ! function_exists( 'hw_hub_illustration' ) ) {
	/**
	 * One of the bundled WDS illustrations.
	 *
	 * @param string $name Illustration name, without the .svg.
	 * @param string $alt  Alt text.
	 * @return string
	 */
	function hw_hub_illustration( $name, $alt = '' ) {
		$name = sanitize_file_name( trim( (string) $name ) );
		$name = preg_replace( '/\.svg$/', '', $name );

		if ( '' === $name || ! file_exists( HW_HUB_PATH . 'assets/illustrations/' . $name . '.svg' ) ) {
			return '';
		}

		return '<img class="hw-hub__illustration" src="' . esc_url( HW_HUB_URL . 'assets/illustrations/' . $name . '.svg' ) . '" alt="' . esc_attr( $alt ) . '" loading="lazy">';
	}
}

