if ( ! function_exists( 'hw_hub_api_events' ) ) {
	/**
	 * Events in a country, from Hostelworld's own events data.
	 *
	 * GET /top/country/{country}/events/ returns each event with real dates for
	 * the current cycle, its city, images and a staff-pick flag. Dated rather
	 * than "every August", which is what a reader planning a trip needs.
	 *
	 * Cached like the hostels feed, with the same behaviour on failure: return
	 * nothing, and let the section fall back to the manual list.
	 *
	 * Countries return a flat list. Continents return staff picks plus groups
	 * by event type, so those are flattened and deduplicated.
	 *
	 * @param array $args country or continent, limit, hours, scope.
	 * @return array
	 */
	function hw_hub_api_events( $args ) {
		$args = wp_parse_args(
			$args,
			array(
				'country' => '',
				'scope'   => 'country',
				'limit'   => 8,
				'hours'   => 24,
			)
		);

		if ( ! $args['country'] ) {
			return array();
		}

		$key    = 'hw_hub_events_' . md5( wp_json_encode( $args ) );
		$cached = get_transient( $key );

		if ( is_array( $cached ) ) {
			return $cached;
		}

		if ( 'city' === $args['scope'] ) {
			$url = sprintf(
				'%s/city/%d/events/',
				untrailingslashit( HW_HUB_API_BASE ),
				(int) $args['country']
			);
		} else {
			$url = sprintf(
				'%s/top/%s/%s/events/',
				untrailingslashit( HW_HUB_API_BASE ),
				'continent' === $args['scope'] ? 'continent' : 'country',
				rawurlencode( sanitize_title( $args['country'] ) )
			);
		}

		$response = wp_remote_get(
			$url,
			array(
				'timeout' => 8,
				'headers' => array( 'Accept' => 'application/json' ),
			)
		);

		if ( is_wp_error( $response ) || 200 !== (int) wp_remote_retrieve_response_code( $response ) ) {
			$stale = hw_hub_api_last_good( $key );

			set_transient( $key, $stale, 5 * MINUTE_IN_SECONDS );

			return $stale;
		}

		$body = json_decode( wp_remote_retrieve_body( $response ), true );
		$raw  = isset( $body['data']['events'] ) ? $body['data']['events'] : array();

		// Continents come back as staffPicks plus groups by event type.
		if ( is_array( $raw ) && ( isset( $raw['staffPicks'] ) || isset( $raw['eventType'] ) ) ) {
			$flat = isset( $raw['staffPicks'] ) ? (array) $raw['staffPicks'] : array();

			if ( ! empty( $raw['eventType'] ) && is_array( $raw['eventType'] ) ) {
				foreach ( $raw['eventType'] as $group ) {
					$flat = array_merge( $flat, (array) $group );
				}
			}

			$raw = $flat;
		}

		$events = array();
		$seen   = array();

		if ( $raw && is_array( $raw ) ) {
			foreach ( $raw as $event ) {
				$id = isset( $event['eventId'] ) ? $event['eventId'] : '';

				if ( $id && isset( $seen[ $id ] ) ) {
					continue;
				}

				$seen[ $id ] = true;
				$image = '';

				foreach ( array( 'large', 'medium', 'small' ) as $size ) {
					if ( ! empty( $event['images'][ $size ] ) ) {
						$image = $event['images'][ $size ];
						break;
					}
				}

				$events[] = array(
					'name'    => isset( $event['name'] ) ? $event['name'] : '',
					'country' => isset( $event['location']['countryName'] ) ? $event['location']['countryName'] : '',
					'blurb'   => isset( $event['description'] ) ? wp_trim_words( $event['description'], 24, '…' ) : '',
					'city'    => isset( $event['location']['name'] ) ? $event['location']['name'] : '',
					'start'   => isset( $event['startDate'] ) ? $event['startDate'] : '',
					'end'     => isset( $event['endDate'] ) ? $event['endDate'] : '',
					'pick'    => ! empty( $event['isStaffPick'] ),
					'score'   => isset( $event['popularityScore'] ) ? (int) $event['popularityScore'] : 0,
					'type'    => isset( $event['eventType'] ) ? $event['eventType'] : '',
					'image'   => $image,
				);
			}
		}

		// Staff picks first, then by popularity, then by date. Anything already
		// finished drops off.
		$today = current_time( 'Y-m-d' );

		$events = array_values(
			array_filter(
				$events,
				function ( $event ) use ( $today ) {
					return '' === $event['end'] || $event['end'] >= $today;
				}
			)
		);

		usort(
			$events,
			function ( $a, $b ) {
				if ( $a['pick'] !== $b['pick'] ) {
					return $a['pick'] ? -1 : 1;
				}

				if ( $a['score'] !== $b['score'] ) {
					return $b['score'] <=> $a['score'];
				}

				return strcmp( $a['start'], $b['start'] );
			}
		);

		$events = array_slice( $events, 0, max( 1, (int) $args['limit'] ) );

		return hw_hub_api_remember( $key, $events, $args['hours'] );
	}
}

if ( ! function_exists( 'hw_hub_event_dates' ) ) {
	/**
	 * "23–27 September" from two ISO dates, or one date where they match.
	 *
	 * @param string $start ISO date.
	 * @param string $end   ISO date.
	 * @return string
	 */
	function hw_hub_event_dates( $start, $end ) {
		if ( ! $start ) {
			return '';
		}

		$start_ts = strtotime( $start );
		$end_ts   = $end ? strtotime( $end ) : $start_ts;

		if ( ! $start_ts ) {
			return '';
		}

		if ( $start_ts === $end_ts ) {
			return date_i18n( 'j F', $start_ts );
		}

		if ( date_i18n( 'F', $start_ts ) === date_i18n( 'F', $end_ts ) ) {
			return date_i18n( 'j', $start_ts ) . '–' . date_i18n( 'j F', $end_ts );
		}

		return date_i18n( 'j M', $start_ts ) . ' – ' . date_i18n( 'j M', $end_ts );
	}
}

if ( ! function_exists( 'hw_hub_api_city_ids' ) ) {
	/**
	 * Every city in a country, name => ID.
	 *
	 * The list carries two ID spaces for the same place — Barcelona appears as
	 * both 83 and 22418 — and only the older, lower one answers on the reviews
	 * and districts endpoints. So the lowest ID per name wins.
	 *
	 * @param int $country_id Hostelworld country ID.
	 * @param int $hours      Cache lifetime.
	 * @return array
	 */
	function hw_hub_api_city_ids( $country_id, $hours = 168 ) {
		$country_id = (int) $country_id;

		if ( ! $country_id ) {
			return array();
		}

		$key    = 'hw_hub_cityids_' . $country_id;
		$cached = get_transient( $key );

		if ( is_array( $cached ) ) {
			return $cached;
		}

		$body = hw_hub_api_get( untrailingslashit( HW_HUB_API_BASE ) . '/country/' . $country_id . '/cities/' );
		$ids  = array();

		if ( ! empty( $body['data']['cities'] ) ) {
			foreach ( $body['data']['cities'] as $city ) {
				if ( empty( $city['name'] ) || empty( $city['id'] ) ) {
					continue;
				}

				$name = hw_hub_city_key( $city['name'] );
				$id   = (int) $city['id'];

				if ( ! isset( $ids[ $name ] ) || $id < $ids[ $name ] ) {
					$ids[ $name ] = $id;
				}
			}
		}

		set_transient( $key, $ids, max( 1, (int) $hours ) * HOUR_IN_SECONDS );

		return $ids;
	}
}

