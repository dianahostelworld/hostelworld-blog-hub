if ( ! function_exists( 'hw_hub_parse_slugs' ) ) {
	/**
	 * Splits a tag expression into slugs. "europe+things-to-do" is two tags.
	 *
	 * @param string $expression Slugs joined by + (spaces around it are fine).
	 * @return array
	 */
	function hw_hub_parse_slugs( $expression ) {
		// sanitize_title turns "Bosnia & Herzegovina" into bosnia-herzegovina,
		// so a country name can be passed straight in.
		$parts = preg_split( '/\s*\+\s*/', trim( (string) $expression ) );

		return array_values( array_filter( array_map( 'sanitize_title', (array) $parts ), 'strlen' ) );
	}
}

if ( ! function_exists( 'hw_hub_tag_for' ) ) {
	/**
	 * The tag a hub means by a slug: the tag with that slug, or failing that
	 * the tag whose name reads the same. Many destination tags carry the
	 * country in the slug (Venice is venice-italy) while the hub was set up
	 * with venice, so a slug-only lookup found nothing and the hub's
	 * carousels and the articles' destination box came up empty.
	 *
	 * @param string $slug Slug as typed in the hub.
	 * @return WP_Term|null
	 */
	function hw_hub_tag_for( $slug ) {
		static $by_name = null;

		$slug = sanitize_title( (string) $slug );

		if ( '' === $slug ) {
			return null;
		}

		$term = get_term_by( 'slug', $slug, 'post_tag' );

		if ( $term && ! is_wp_error( $term ) ) {
			return $term;
		}

		if ( null === $by_name ) {
			$by_name = array();
			$terms   = get_terms( array( 'taxonomy' => 'post_tag', 'hide_empty' => false ) );

			foreach ( is_wp_error( $terms ) ? array() : $terms as $tag ) {
				$key = sanitize_title( $tag->name );

				// Two tags with one name: the one with more articles.
				if ( ! isset( $by_name[ $key ] ) || $tag->count > $by_name[ $key ]->count ) {
					$by_name[ $key ] = $tag;
				}
			}
		}

		return isset( $by_name[ $slug ] ) ? $by_name[ $slug ] : null;
	}
}

if ( ! function_exists( 'hw_hub_resolve_terms' ) ) {
	/**
	 * Looks each slug up in the destination taxonomy first, then in tags.
	 *
	 * Returns false if any slug matches nothing. That matters: the tags are
	 * ANDed, so a missing one means the real answer is "no posts" — quietly
	 * dropping it would widen the section to something nobody asked for.
	 *
	 * @param string|array $slugs Tag expression or list of slugs.
	 * @return array|false Terms, or false if one could not be found.
	 */
	function hw_hub_resolve_terms( $slugs ) {
		$slugs = is_array( $slugs ) ? $slugs : hw_hub_parse_slugs( $slugs );

		if ( ! $slugs ) {
			return false;
		}

		$taxonomies = array( 'post_tag' );
		$terms      = array();

		foreach ( $slugs as $slug ) {
			$found = false;

			foreach ( $taxonomies as $taxonomy ) {
				$term = 'post_tag' === $taxonomy ? hw_hub_tag_for( $slug ) : get_term_by( 'slug', $slug, $taxonomy );

				if ( $term && ! is_wp_error( $term ) ) {
					$terms[] = $term;
					$found   = true;
					break;
				}
			}

			if ( ! $found ) {
				return false;
			}
		}

		return $terms;
	}
}

if ( ! function_exists( 'hw_hub_get_posts' ) ) {
	/**
	 * The newest posts carrying every tag in the expression.
	 *
	 * @param string $expression Tag expression, e.g. "europe+things-to-do".
	 * @param int    $count      How many to return.
	 * @return array
	 */
	function hw_hub_get_posts( $expression, $count = 4 ) {
		$terms = hw_hub_resolve_terms( $expression );

		if ( ! $terms ) {
			return array();
		}

		$tax_query = array( 'relation' => 'AND' );

		// One clause per term, so they narrow each other rather than pile into
		// a single OR'd list.
		foreach ( $terms as $term ) {
			$tax_query[] = array(
				'taxonomy' => $term->taxonomy,
				'field'    => 'term_id',
				'terms'    => $term->term_id,
			);
		}

		$args = array(
			'post_type'           => 'post',
			'posts_per_page'      => $count,
			'ignore_sticky_posts' => true,
			'no_found_rows'       => true,
			'tax_query'           => $tax_query, // phpcs:ignore WordPress.DB.SlowDBQuery
		);

		// Polylang doesn't filter secondary queries on its own, which is how a
		// Spanish and a Japanese post land in an English row.
		if ( function_exists( 'pll_current_language' ) ) {
			$args['lang'] = pll_current_language( 'slug' );
		}

		$query = new WP_Query( $args );

		return $query->posts;
	}
}

if ( ! function_exists( 'hw_hub_term_filter_url' ) ) {
	/**
	 * An archive URL filtered to the same tags the section queried, so the
	 * "see all" button lands on the wider version of exactly what's on screen.
	 *
	 * A resolved single term gets its own pretty archive. Everything else is
	 * built with core's AND syntax: /?tag=europe%2Bfood. %2B rather than a
	 * literal +, which would decode to a space and match nothing.
	 *
	 * The URL is built from the slugs whether or not the terms exist yet — an
	 * archive that is currently empty is still the right destination, and it
	 * fills up on its own as posts get tagged.
	 *
	 * @param string $expression Tag expression.
	 * @return string
	 */
	function hw_hub_term_filter_url( $expression ) {
		$slugs = hw_hub_parse_slugs( $expression );

		if ( ! $slugs ) {
			return '';
		}

		$terms = hw_hub_resolve_terms( $slugs );

		if ( $terms && 1 === count( $terms ) ) {
			$link = get_term_link( $terms[0] );

			if ( ! is_wp_error( $link ) ) {
				return $link;
			}
		}

		// Group by taxonomy so each one's query var carries its own slugs.
		// Unresolved slugs are treated as tags, which is what they will be.
		$grouped = array();

		foreach ( $slugs as $slug ) {
			$term = $terms ? hw_hub_term_for_slug( $terms, $slug ) : null;
			$var  = 'tag';

			if ( $term ) {
				$taxonomy = get_taxonomy( $term->taxonomy );
				$var      = ( $taxonomy && $taxonomy->query_var ) ? $taxonomy->query_var : $term->taxonomy;
			}

			$grouped[ $var ][] = rawurlencode( $slug );
		}

		$args = array();

		foreach ( $grouped as $var => $list ) {
			$args[] = rawurlencode( $var ) . '=' . implode( '%2B', $list );
		}

		return home_url( '/?' . implode( '&', $args ) );
	}
}

if ( ! function_exists( 'hw_hub_term_for_slug' ) ) {
	/**
	 * Finds a term in a resolved set by its slug.
	 *
	 * @param array  $terms Resolved terms.
	 * @param string $slug  Slug to match.
	 * @return WP_Term|null
	 */
	function hw_hub_term_for_slug( $terms, $slug ) {
		foreach ( (array) $terms as $term ) {
			if ( $term->slug === $slug ) {
				return $term;
			}
		}

		return null;
	}
}

