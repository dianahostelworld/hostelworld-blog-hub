/* ---------- Link resolution ---------------------------------------------- */

if ( ! function_exists( 'hw_hub_url' ) ) {
	/**
	 * Turns a config reference into a real URL, or an empty string if the
	 * target doesn't exist. Never returns a guessed URL.
	 */
	function hw_hub_url( $ref ) {
		$ref = trim( (string) $ref );

		if ( '' === $ref ) {
			return '';
		}
		if ( '#' === $ref[0] || 0 === strpos( $ref, 'http://' ) || 0 === strpos( $ref, 'https://' ) ) {
			return $ref;
		}
		if ( 0 === strpos( $ref, 'page:' ) ) {
			$page = get_page_by_path( substr( $ref, 5 ) );
			return $page ? get_permalink( $page ) : '';
		}
		if ( 0 === strpos( $ref, 'tags:' ) ) {
			return hw_hub_term_filter_url( substr( $ref, 5 ) );
		}
		if ( 0 === strpos( $ref, 'term:' ) ) {
			$bits = explode( ':', $ref );
			if ( count( $bits ) < 3 || ! taxonomy_exists( $bits[1] ) ) {
				return '';
			}
			$term = get_term_by( 'slug', $bits[2], $bits[1] );
			if ( ! $term || is_wp_error( $term ) ) {
				return '';
			}
			$link = get_term_link( $term );
			return is_wp_error( $link ) ? '' : $link;
		}
		return '';
	}
}

if ( ! function_exists( 'hw_hub_taxonomy' ) ) {
	/**
	 * The taxonomy articles are pulled from: tags, always.
	 *
	 * A destination exists three times over — as a Page (the hub itself), as a
	 * term in the destination taxonomy (for structure), and as a tag (what
	 * articles carry). The hub fetches the tag. It never queries the Page or
	 * the structural term, because articles aren't attached to those.
	 *
	 * @return string
	 */
	function hw_hub_taxonomy() {
		return 'post_tag';
	}
}

if ( ! function_exists( 'hw_hub_link_open' ) ) {
	/** Opens <a href> when the link resolves, <div> when it doesn't. */
	function hw_hub_link_open( $url, $class, $extra = '' ) {
		$tag = $url ? 'a' : 'div';
		$out = '<' . $tag . ' class="' . esc_attr( $class ) . '"';
		if ( $url ) {
			$out .= ' href="' . esc_url( $url ) . '"';
		}
		return $out . ' ' . $extra . '>';
	}
}

if ( ! function_exists( 'hw_hub_link_close' ) ) {
	function hw_hub_link_close( $url ) {
		return $url ? '</a>' : '</div>';
	}
}

