		}

		return sprintf( _n( '%s guide', '%s guides', $term->count, 'hostelworld' ), number_format_i18n( $term->count ) );
	}
}

if ( ! function_exists( 'hw_hub_missing_slugs' ) ) {
	/**
	 * Slugs in an expression that match no term.
	 *
	 * A row with an unresolved tag has nothing to show, but vanishing without a
	 * word looks like the section was deleted. Editors get told which tag is
	 * missing; visitors just don't see the row.
	 *
	 * @param string $expression Tag expression.
	 * @return array
	 */
	function hw_hub_missing_slugs( $expression ) {
		$taxonomies = array( 'post_tag' );
		$missing    = array();

		foreach ( hw_hub_parse_slugs( $expression ) as $slug ) {
			$found = false;

			foreach ( $taxonomies as $taxonomy ) {
				$term = get_term_by( 'slug', $slug, $taxonomy );

				if ( $term && ! is_wp_error( $term ) ) {
					$found = true;
					break;
				}
			}

			if ( ! $found ) {
				$missing[] = $slug;
			}
		}

		return $missing;
	}
}

if ( ! function_exists( 'hw_hub_row_expression' ) ) {
	/**
	 * The tag expression a row actually queries.
	 *
	 * With scoping on, the hub's own term is added unless it's already listed,
	 * so a row saved as "things-to-do" can't return Bangkok on a Europe hub.
	 * Turn the setting off in Settings to query exactly what's typed.
	 *
	 * @param array  $config Hub config.
	 * @param string $tag    The row's tag expression.
	 * @return string
	 */
	function hw_hub_row_expression( $config, $tag ) {
		$slugs = hw_hub_parse_slugs( $tag );

		if ( empty( $config['scope_rows'] ) || empty( $config['hub_term'] ) ) {
			return implode( '+', $slugs );
		}

		$hub_term = sanitize_title( $config['hub_term'] );

		if ( ! in_array( $hub_term, $slugs, true ) ) {
			array_unshift( $slugs, $hub_term );
		}

		return implode( '+', $slugs );
	}
}

if ( ! function_exists( 'hw_hub_card_labels' ) ) {
	/**
	 * The two small labels on an article card.
	 *
	 * Both are read off the post itself. The hub name is only shown when the
	 * post genuinely carries the hub term — printing it regardless labelled a
	 * Bangkok guide as Europe.
	 *
	 * @param int   $post_id Post ID.
	 * @param array $config  Hub config.
	 * @return array primary label, and whether the post is in this hub.
	 */
	function hw_hub_card_labels( $post_id, $config ) {
		$hub_term = sanitize_title( $config['hub_term'] );
		$primary  = '';
		$in_hub   = false;

		foreach ( array( 'post_tag' ) as $tax ) {
			$terms = get_the_terms( $post_id, $tax );

			if ( ! $terms || is_wp_error( $terms ) ) {
				continue;
			}

			foreach ( $terms as $term ) {
				if ( $term->slug === $hub_term ) {
					$in_hub = true;
					continue;
				}

				if ( '' === $primary ) {
					$primary = $term->name;
				}
			}

			if ( '' !== $primary && $in_hub ) {
				break;
			}
		}

		return array(
			'primary' => $primary,
			'in_hub'  => $in_hub,
		);
	}
}

if ( ! function_exists( 'hw_hub_count_posts' ) ) {
	/**
	 * How many published posts carry every tag in an expression.
	 *
	 * @param string $expression Tag expression.
	 * @return int
	 */
	function hw_hub_count_posts( $expression ) {
		$terms = hw_hub_resolve_terms( $expression );

		if ( ! $terms ) {
			return 0;
		}

		$tax_query = array( 'relation' => 'AND' );

		foreach ( $terms as $term ) {
			$tax_query[] = array(
				'taxonomy' => $term->taxonomy,
				'field'    => 'term_id',
				'terms'    => $term->term_id,
			);
		}

		$query = new WP_Query(
			array(
				'post_type'      => 'post',
				'post_status'    => 'publish',
				'posts_per_page' => 1,
				'fields'         => 'ids',
				'tax_query'      => $tax_query, // phpcs:ignore WordPress.DB.SlowDBQuery
			)
		);

		return (int) $query->found_posts;
	}
}

