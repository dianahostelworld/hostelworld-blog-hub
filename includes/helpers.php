	/**
	 * An official WDS icon as inline SVG.
	 *
	 * Taken from the Hostelworld icon library and recoloured to currentColor so
	 * each one picks up its context's colour. Nothing is hosted or requested;
	 * the markup is inlined.
	 *
	 * @param string $name Icon name, as listed in hw_hub_icon_names().
	 * @param int    $size Pixel size.
	 * @return string
	 */
	function hw_hub_icon( $name, $size = 16 ) {
		$paths = hw_hub_icon_paths();

		if ( ! isset( $paths[ $name ] ) ) {
			return '';
		}

