if ( ! function_exists( 'hw_hub_pick_review' ) ) {
	/**
	 * The most presentable review in a set, or nothing.
	 *
	 * These are raw traveller reviews, so most are unusable on a page like
	 * this: fragments, all caps, no punctuation, or a stray question mark in
	 * the middle of a sentence. Anything that does not read as a finished
	 * thought is rejected rather than tidied — editing someone's words and
	 * still attributing them is worse than showing nothing.
	 *
	 * @param array $reviews Review list from the API.
	 * @return array|null text and rating.
	 */
	function hw_hub_pick_review( $reviews ) {
		$candidates = array();

		foreach ( (array) $reviews as $review ) {
			$text   = isset( $review['reviewText'] ) ? trim( preg_replace( '/\s+/', ' ', $review['reviewText'] ) ) : '';
			$rating = isset( $review['rating'] ) ? (float) $review['rating'] : 0;

			if ( '' === $text ) {
				continue;
			}

			$words = str_word_count( $text );

			// Long enough to be a thought, short enough for a card.
			if ( $words < 8 || strlen( $text ) > 180 ) {
				continue;
			}

			// Has to start like a sentence and end like one.
			if ( ! preg_match( '/^[A-Z]/', $text ) || ! preg_match( '/[.!]$/', $text ) ) {
				continue;
			}

			// Mid-sentence question marks and stray punctuation runs read as typos.
			if ( preg_match( '/[?]/', $text ) || preg_match( '/[.!,]{2,}/', $text ) ) {
				continue;
			}

			// Shouting, or no lower case at all.
			if ( $text === strtoupper( $text ) ) {
				continue;
			}

			// Only glowing ones: this sits on a page selling the city.
			if ( $rating && $rating < 9 ) {
				continue;
			}

			$candidates[] = array(
				'text'   => $text,
				'rating' => $rating,
				'words'  => $words,
			);
		}

		if ( ! $candidates ) {
			return null;
		}

		// Prefer the fullest one.
		usort(
			$candidates,
			function ( $a, $b ) {
				return $b['words'] <=> $a['words'];
			}
		);

		return $candidates[0];
	}
}

if ( ! function_exists( 'hw_hub_api_city_data' ) ) {
	/**
	 * Supply and a traveller quote for each city named on the page.
	 *
	 * Each city is resolved by name — /city/{city}/{country}/ returns its ID and
	 * how many properties it has — then that ID fetches its review summary. The
	 * top-cities endpoint only ever returns five per country, which is why
	 * Granada and San Sebastián came back empty before.
	 *
	 * Deliberately no prices here: see hw_hub_city_prices_from_feed().
	 *
	 * @param array $args country, cities (list of names), hours.
	 * @return array city name (lowercase) => data
	 */
	function hw_hub_api_city_data( $args ) {
		$args = wp_parse_args(
			$args,
			array(
				'country' => '',
				'cities'  => array(),
				'hours'   => 24,
			)
		);

		if ( ! $args['country'] || ! $args['cities'] ) {
			return array();
		}

		$key    = 'hw_hub_cities_' . md5( wp_json_encode( $args ) );
		$cached = get_transient( $key );

		if ( is_array( $cached ) ) {
			return $cached;
		}

		$base    = untrailingslashit( HW_HUB_API_BASE );
		$country = sanitize_title( $args['country'] );
		$out     = array();

		foreach ( $args['cities'] as $name ) {
			$name = trim( (string) $name );

			if ( '' === $name ) {
				continue;
			}

			$info = hw_hub_api_get( $base . '/city/' . rawurlencode( sanitize_title( $name ) ) . '/' . rawurlencode( $country ) . '/' );
			$city = isset( $info['data'] ) ? $info['data'] : array();

			if ( empty( $city['id'] ) ) {
				continue;
			}

			$entry = array(
				'properties' => isset( $city['totalPropertiesAvailable'] ) ? (int) $city['totalPropertiesAvailable'] : 0,
				'city_id'    => (int) $city['id'],
				'review'     => '',
				'rating'     => 0,
			);

			$summary = hw_hub_api_get( $base . '/city-reviews/' . $entry['city_id'] . '/summary/?limit=10' );
			$review  = hw_hub_pick_review( isset( $summary['data']['reviews'] ) ? $summary['data']['reviews'] : array() );

			if ( $review ) {
				$entry['review'] = $review['text'];
				$entry['rating'] = $review['rating'];
			}

			$out[ strtolower( $name ) ] = $entry;
		}

		return hw_hub_api_remember( $key, $out, $args['hours'] );
	}
}

if ( ! function_exists( 'hw_hub_pick_review' ) ) {
	/**
	 * The best usable quote out of a city's review summary, or nothing.
	 *
	 * These are raw traveller reviews, so most of them are not publishable: one
	 * word, no punctuation, a question mark where a full stop should be. The
	 * rules below are blunt on purpose — it is better to show no quote than a
	 * bad one on a page meant to sell the place.
	 *
	 * @param array $reviews Review summary rows.
	 * @return array|null text and rating.
	 */
	function hw_hub_pick_review( $reviews ) {
		$best = null;

		foreach ( (array) $reviews as $review ) {
			$text   = isset( $review['reviewText'] ) ? trim( preg_replace( '/\s+/u', ' ', $review['reviewText'] ) ) : '';
			$rating = isset( $review['rating'] ) ? (float) $review['rating'] : 0;

			// Enthusiastic enough to be worth quoting.
			if ( $rating < 9 ) {
				continue;
			}

			$length = function_exists( 'mb_strlen' ) ? mb_strlen( $text ) : strlen( $text );

			// Long enough to say something, short enough for a card.
			if ( $length < 45 || $length > 165 ) {
				continue;
			}

			// At least a proper sentence: starts as one, ends as one.
			if ( ! preg_match( '/^[A-ZÀ-Þ]/u', $text ) || ! preg_match( '/[.!]$/u', $text ) ) {
				continue;
			}

			// Hedging, questions and run-on punctuation read badly in a pull quote.
			if ( preg_match( '/[?]|\.\.|!!|\bidk\b/iu', $text ) ) {
				continue;
			}

			if ( str_word_count( $text ) < 9 ) {
				continue;
			}

			// These are property reviews as often as city ones. "We loved the
			// Eco Hostel, great location, clean, ac." says nothing about Granada.
			if ( preg_match( '/\b(hostel|hotel|room|dorm|staff|reception|shower|breakfast|check-?in|bed)\b/iu', $text ) ) {
				continue;
			}

			if ( ! $best || $rating > $best['rating'] || ( $rating === $best['rating'] && $length > $best['length'] ) ) {
				$best = array(
					'text'   => $text,
					'rating' => $rating,
					'length' => $length,
				);
			}
		}

		return $best;
	}
}

if ( ! function_exists( 'hw_hub_city_prices_from_feed' ) ) {
	/**
	 * Cheapest dorm price per city, taken from the property feed already
	 * fetched for the hostels carousel. Every figure belongs to a named
	 * property rather than an aggregate nobody can check.
	 *
	 * @param array $hostels Result of hw_hub_api_hostels().
	 * @return array city name (lowercase) => array( price, currency )
	 */
	function hw_hub_city_prices_from_feed( $hostels ) {
		$prices = array();

		foreach ( (array) $hostels as $hostel ) {
			if ( empty( $hostel['city'] ) || empty( $hostel['dorm'] ) || empty( $hostel['price']['value'] ) ) {
				continue;
			}

			$name  = strtolower( $hostel['city'] );
			$value = (float) $hostel['price']['value'];

			if ( ! isset( $prices[ $name ] ) || $value < $prices[ $name ]['value'] ) {
				$prices[ $name ] = array(
					'value'    => $value,
					'currency' => isset( $hostel['price']['currency'] ) ? $hostel['price']['currency'] : 'EUR',
				);
			}
		}

		return $prices;
	}
}

if ( ! function_exists( 'hw_hub_api_remember' ) ) {
	/**
	 * Caches a successful API result twice: once for the normal refresh window,
	 * and once as a week-long backup.
	 *
	 * The API is occasionally flaky — the continent events endpoint returned a
	 * 500 and then a 200 a minute later — and a section that empties itself
	 * because of one bad response is worse than a section showing yesterday's
	 * answer.
	 *
	 * @param string $key   Transient key.
	 * @param array  $value Result.
	 * @param int    $hours Normal cache lifetime.
	 * @return array
	 */
	function hw_hub_api_remember( $key, $value, $hours ) {
		set_transient( $key, $value, max( 1, (int) $hours ) * HOUR_IN_SECONDS );

		if ( $value ) {
			set_transient( $key . '_bak', $value, WEEK_IN_SECONDS );
		}

		return $value;
	}
}

if ( ! function_exists( 'hw_hub_api_last_good' ) ) {
	/**
	 * The last successful result for a call, if there is one.
	 *
	 * @param string $key Transient key.
	 * @return array
	 */
	function hw_hub_api_last_good( $key ) {
		$backup = get_transient( $key . '_bak' );

		return is_array( $backup ) ? $backup : array();
	}
}

if ( ! function_exists( 'hw_hub_api_get' ) ) {
	/**
	 * A decoded GET against the Static Pages API, or an empty array.
	 *
	 * @param string $url Full URL.
	 * @return array
	 */
	function hw_hub_api_get( $url ) {
		$response = wp_remote_get(
			$url,
			array(
				'timeout' => 8,
				'headers' => array( 'Accept' => 'application/json' ),
			)
		);

		if ( is_wp_error( $response ) || 200 !== (int) wp_remote_retrieve_response_code( $response ) ) {
			return array();
		}

		$body = json_decode( wp_remote_retrieve_body( $response ), true );

		return is_array( $body ) ? $body : array();
	}
}

if ( ! function_exists( 'hw_hub_api_price_value' ) ) {
	/**
	 * The number out of a {value, currency} price, or 0.
	 *
	 * @param mixed $price Price structure.
	 * @return float
	 */
	function hw_hub_api_price_value( $price ) {
		if ( is_array( $price ) && isset( $price['value'] ) ) {
			return (float) $price['value'];
		}

		return is_numeric( $price ) ? (float) $price : 0;
	}
}

if ( ! function_exists( 'hw_hub_city_itineraries' ) ) {
	/**
	 * A city's itinerary links, as entered on the Page.
	 *
	 * Stored as "3 days=https://…; 24 hours=https://…" in one cell and edited
	 * as rows in the panel. Rows without a URL are dropped, so a city shows
	 * exactly as many links as it has articles — five, two, or none.
	 *
	 * @param string $value Cell value.
	 * @return array
	 */
	function hw_hub_city_itineraries( $value ) {
		$out = array();

		foreach ( explode( ';', (string) $value ) as $entry ) {
			$parts = explode( '=', $entry, 2 );

			if ( count( $parts ) < 2 ) {
				continue;
			}

			$label = trim( $parts[0] );
			$url   = hw_hub_url( trim( $parts[1] ) );

			if ( '' === $label || '' === $url ) {
				continue;
			}

			$out[] = array(
				'label' => $label,
				'url'   => $url,
			);
		}

		return $out;
	}
}

if ( ! function_exists( 'hw_hub_api_city_reviews' ) ) {
	/**
	 * A city's traveller reviews, for the picker on the edit screen.
	 *
	 * The endpoint returns three by default, which is why several cities had
	 * nothing worth quoting; ten gives something to choose from. Everything is
	 * returned, good and bad, because the whole point is that a person picks.
	 *
	 * @param string $city    City name.
	 * @param string $country Country name.
	 * @param int    $hours   Cache lifetime.
	 * @return array text, rating and whether it passes the automatic filter.
	 */
	function hw_hub_api_city_reviews( $city, $country, $hours = 24 ) {
		$city    = trim( (string) $city );
		$country = trim( (string) $country );

		if ( '' === $city || '' === $country ) {
			return array();
		}

		$key    = 'hw_hub_reviews_' . md5( $city . '|' . $country );
		$cached = get_transient( $key );

		if ( is_array( $cached ) ) {
			return $cached;
		}

		$base = untrailingslashit( HW_HUB_API_BASE );
		$info = hw_hub_api_get( $base . '/city/' . rawurlencode( sanitize_title( $city ) ) . '/' . rawurlencode( sanitize_title( $country ) ) . '/' );

		if ( empty( $info['data']['id'] ) ) {
			set_transient( $key, array(), HOUR_IN_SECONDS );
			return array();
		}

		$summary = hw_hub_api_get( $base . '/city-reviews/' . (int) $info['data']['id'] . '/summary/?limit=10' );
		$out     = array();

		foreach ( ( isset( $summary['data']['reviews'] ) ? $summary['data']['reviews'] : array() ) as $review ) {
			$text = isset( $review['reviewText'] ) ? trim( preg_replace( '/\s+/u', ' ', $review['reviewText'] ) ) : '';

			if ( '' === $text ) {
				continue;
			}

			$out[] = array(
				'text'   => $text,
				'rating' => isset( $review['rating'] ) ? (float) $review['rating'] : 0,
				'good'   => (bool) hw_hub_pick_review( array( $review ) ),
			);
		}

		usort(
			$out,
			function ( $a, $b ) {
				if ( $a['good'] !== $b['good'] ) {
					return $a['good'] ? -1 : 1;
				}

				return $b['rating'] <=> $a['rating'];
			}
		);

		return hw_hub_api_remember( $key, $out, $hours );
	}
}

