if ( ! function_exists( 'hw_hub_country_url' ) ) {
	/**
	 * A country's URL: this hub's own address plus the country slug.
	 *
	 * On a hub at /blog/europe/, Spain is /blog/europe/spain/. That holds
	 * whether or not the country page exists yet, and it is the same URL the
	 * country page will have once it is created as a child of this hub, so
	 * nothing needs relinking later.
	 *
	 * @param string $name     Country name as shown in the grid.
	 * @param string $override Optional path or URL typed into the editor.
	 * @return string
	 */
	function hw_hub_country_url( $name, $override = '' ) {
		$override = trim( (string) $override );

		if ( '' !== $override ) {
			if ( 0 === strpos( $override, 'http://' ) || 0 === strpos( $override, 'https://' ) ) {
				return $override;
			}

			return home_url( '/' . ltrim( $override, '/' ) . '/' );
		}

		$slug = sanitize_title( $name );

		if ( '' === $slug ) {
			return '';
		}

		return trailingslashit( get_permalink( get_the_ID() ) ) . $slug . '/';
	}
}

if ( ! function_exists( 'hw_hub_api_hostels' ) ) {
	/**
	 * Top-rated properties for a continent, from Hostelworld's Static Pages API.
	 *
	 * GET /top/properties-in-popular-cities/{type}/{location-type}/{id}/?currency=
	 * returns the most popular cities in that location, each with its own top
	 * properties. They are flattened and re-sorted by rating so the carousel is
	 * genuinely "best in Europe" rather than "best per city, city by city".
	 *
	 * The response is cached, so the page serves from the database and the API
	 * sees one request per cache window rather than one per visitor. A failed
	 * or slow call returns nothing and the section falls back to the manual
	 * list, so the page never waits on an outage.
	 *
	 * Always production: the base URL is a constant, not a setting.
	 *
	 * @param array $args location_type, location_id, currency, limit, hours, type.
	 * @return array
	 */
	function hw_hub_api_hostels( $args ) {
		$args = wp_parse_args(
			$args,
			array(
				'type'          => 'hostel',
				'location_type' => 'continent',
				'location_id'   => '3',
				'currency'      => 'EUR',
				'limit'         => 12,
				'hours'         => 12,
				'min_reviews'   => 100,
			)
		);

		if ( ! $args['location_id'] ) {
			return array();
		}

		$key    = 'hw_hub_api_' . md5( wp_json_encode( $args ) );
		$cached = get_transient( $key );

		if ( is_array( $cached ) ) {
			return $cached;
		}

		$url = sprintf(
			'%s/top/properties-in-popular-cities/%s/%s/%s/?currency=%s',
			untrailingslashit( HW_HUB_API_BASE ),
			rawurlencode( $args['type'] ),
			rawurlencode( $args['location_type'] ),
			rawurlencode( $args['location_id'] ),
			rawurlencode( $args['currency'] )
		);

		$response = wp_remote_get(
			$url,
			array(
				'timeout' => 8,
				'headers' => array(
					'Accept'          => 'application/json',
					'Accept-Language' => substr( get_locale(), 0, 2 ),
				),
			)
		);

		if ( is_wp_error( $response ) || 200 !== (int) wp_remote_retrieve_response_code( $response ) ) {
			// Don't hammer a broken endpoint, and show the last good answer
			// rather than an empty shelf.
			$stale = hw_hub_api_last_good( $key );

			set_transient( $key, $stale, 5 * MINUTE_IN_SECONDS );

			return $stale;
		}

		$body = json_decode( wp_remote_retrieve_body( $response ), true );
		$out  = array();

		$seen = array();

		if ( ! empty( $body['data']['cities'] ) && is_array( $body['data']['cities'] ) ) {
			foreach ( $body['data']['cities'] as $city ) {
				if ( empty( $city['properties'] ) || ! is_array( $city['properties'] ) ) {
					continue;
				}

				$city_key = isset( $city['id'] ) ? (string) $city['id'] : (string) $city['name'];

				foreach ( $city['properties'] as $property ) {
					// The feed repeats properties across its city blocks.
					$id = isset( $property['id'] ) ? (int) $property['id'] : 0;

					if ( $id && isset( $seen[ $id ] ) ) {
						continue;
					}

					$seen[ $id ] = true;

					$out[ $city_key ][] = array(
						'name'     => isset( $property['name'] ) ? $property['name'] : '',
						'city'     => isset( $city['name'] ) ? $city['name'] : '',
						'country'  => isset( $city['country'] ) ? $city['country'] : '',
						'rating'   => isset( $property['avgRating'] ) ? (float) $property['avgRating'] : 0,
						'reviews'  => isset( $property['numberReviews'] ) ? (int) $property['numberReviews'] : 0,
						'distance' => isset( $property['cityCenterDistance'] ) ? (float) $property['cityCenterDistance'] : null,
						'price'    => isset( $property['sharedMinPrice']['value'] ) ? $property['sharedMinPrice'] : ( isset( $property['privateMinPrice'] ) ? $property['privateMinPrice'] : null ),
						'dorm'     => isset( $property['sharedMinPrice']['value'] ),
						'image'    => hw_hub_api_image( $property ),
						'url'      => hw_hub_api_property_url( $property ),
						'eco'      => ! empty( $property['sustainability'][0]['category_title'] ) ? $property['sustainability'][0]['category_title'] : '',
					);
				}
			}
		}

		// A 10.0 from 40 reviews outranks a 9.9 from 8,000, which is not what a
		// reader means by "best". Thin samples are held back unless dropping
		// them would leave too little to show.
		$min = (int) $args['min_reviews'];

		foreach ( $out as $city_key => $list ) {
			$strong = array_values(
				array_filter(
					$list,
					function ( $item ) use ( $min ) {
						return $item['reviews'] >= $min;
					}
				)
			);

			if ( count( $strong ) >= 2 ) {
				$out[ $city_key ] = $strong;
			}
		}

		// Rating order within each city...
		foreach ( $out as $city_key => $list ) {
			usort(
				$list,
				function ( $a, $b ) {
					if ( $a['rating'] === $b['rating'] ) {
						return $b['reviews'] <=> $a['reviews'];
					}

					return $b['rating'] <=> $a['rating'];
				}
			);

			$out[ $city_key ] = $list;
		}

		// ...then one city at a time across the row. Straight rating order puts
		// five Barcelona hostels in a row, which is not what "best in Europe"
		// should look like on a continent hub.
		$mixed = array();
		$round = 0;

		while ( $out ) {
			foreach ( $out as $city_key => $list ) {
				if ( ! isset( $list[ $round ] ) ) {
					unset( $out[ $city_key ] );
					continue;
				}

				$mixed[] = $list[ $round ];
			}

			++$round;

			if ( $round > 50 ) {
				break;
			}
		}

		$out = array_slice( $mixed, 0, max( 1, (int) $args['limit'] ) );

		return hw_hub_api_remember( $key, $out, $args['hours'] );
	}
}

