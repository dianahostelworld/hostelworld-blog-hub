if ( ! function_exists( 'hw_hub_api_city_details' ) ) {
	/**
	 * Supply, cheapest district price and a traveller quote for one city.
	 *
	 * @param int  $city_id City ID.
	 * @param int  $hours   Cache lifetime.
	 * @return array
	 */
	function hw_hub_api_city_details( $city_id, $hours = 24 ) {
